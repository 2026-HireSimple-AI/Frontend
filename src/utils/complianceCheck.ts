const FORBIDDEN_KEYWORDS = [
  "결혼", "혼인", "출산", "임신", "육아", "자녀",
  "나이", "연령", "고향", "출신지역", "출신지", "출신학교", "학벌", "학력",
  "가족관계", "가족사항", "부모님", "형제", "자매",
  "종교", "정치", "신체조건", "외모", "키", "몸무게",
];

const WARNING_KEYWORDS = [
  "야근", "주말근무", "주말 근무", "지방발령", "지방 발령", "군복무", "군 복무",
  "초과근무", "야간근무",
];

export type ComplianceStatus = "준수" | "경고" | "심각";

export function checkComplianceLocally(text: string): {
  status: ComplianceStatus;
  matchedKeyword: string | null;
} {
  const normalized = text.replace(/\s+/g, "");

  for (const kw of FORBIDDEN_KEYWORDS) {
    if (normalized.includes(kw) || text.includes(kw)) {
      return { status: "심각", matchedKeyword: kw };
    }
  }

  for (const kw of WARNING_KEYWORDS) {
    if (normalized.includes(kw.replace(/\s/g, "")) || text.includes(kw)) {
      return { status: "경고", matchedKeyword: kw };
    }
  }

  return { status: "준수", matchedKeyword: null };
}

